/** Korean particles for dynamically inserted stems, branches and term names. */
export function withParticle(
  word: string,
  pair: '은/는' | '이/가' | '을/를' | '으로/로' | '이에요/예요',
): string {
  const pronounced = word.replace(/\([^)]*\)$/, '')
  const code = pronounced.charCodeAt(pronounced.length - 1) - 0xac00
  const final = code >= 0 && code <= 11171 ? code % 28 : 0
  const [consonant, vowel] = pair.split('/')
  return (
    word +
    (final !== 0 && !(pair === '으로/로' && final === 8) ? consonant : vowel)
  )
}
