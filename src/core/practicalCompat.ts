export function practicalFact(fact: CompatFact): PracticalCopy | null {
  if (Object.prototype.hasOwnProperty.call(MBTI, fact.code))
    return MBTI[fact.code][fact.kind] ?? null
  const expected =
    fact.code === 'controls' || fact.code === 'branch-clash'
      ? 'difference'
      : 'match'
  return Object.prototype.hasOwnProperty.call(SAJU, fact.code) &&
    fact.kind === expected
    ? SAJU[fact.code]
    : null
}
export function practicalCompat(pair: PairCompat) {
  const cards: (PracticalCopy & {
    key: string
    kind: CompatFact['kind']
    source: string
    bases: string[]
  })[] = []
  const extra: CompatFact[] = []
  for (const fact of pair.facts) {
    const copy = practicalFact(fact)
    if (!copy) {
      extra.push(fact)
      continue
    }
    const key = `${fact.code}:${fact.kind}`
    const existing = cards.find((card) => card.key === key)
    if (existing) {
      if (!existing.bases.includes(fact.text)) existing.bases.push(fact.text)
      continue
    }
    cards.push({
      ...copy,
      key,
      kind: fact.kind,
      source: fact.code.startsWith('mbti-')
        ? '직접 공개한 MBTI'
        : '전통 사주 비교',
      bases: [fact.text],
    })
  }
  // Differences first for reading order; this is not a severity/risk ranking.
  cards.sort((a, b) => Number(a.kind === 'match') - Number(b.kind === 'match'))
  return {
    cards,
    extra,
    strengths: cards.filter((c) => c.kind === 'match'),
    adjustments: cards.filter((c) => c.kind === 'difference'),
  }
}
